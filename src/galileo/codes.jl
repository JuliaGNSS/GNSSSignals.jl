const GALILEO_CS100_LENGTH = 100

"""
$(SIGNATURES)

Build the 100 × 50 Galileo CS100 secondary-code matrix from
`GALILEO_CS100_HEX`. Column `n` is SVID `n`'s CS100ₙ overlay, decoded MSB-first
and mapped `0 -> -1`, `1 -> +1`.

Used by both [`GalileoE5aQ`](@ref) and [`GalileoE6C`](@ref), whose ICDs assign
each the same CS100_1-50.
"""
function _build_galileo_cs100_secondary()
    codes = Matrix{Int8}(undef, GALILEO_CS100_LENGTH, length(GALILEO_CS100_HEX))
    for (prn, hex) in enumerate(GALILEO_CS100_HEX)
        chip = 0
        for c in hex
            nibble = parse(Int, string(c); base = 16)
            for shift = 3:-1:0
                chip += 1
                chip > GALILEO_CS100_LENGTH && break
                @inbounds codes[chip, prn] = Int8(2 * ((nibble >> shift) & 1) - 1)
            end
        end
    end
    codes
end
