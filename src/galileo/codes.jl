them: the E5a-Q pilot (Galileo OS SIS ICD v2.2 §3.5.2, Table 24) and the E6-C
pilot (E6-B/C Codes Technical Note §2.4, Table 2, which reproduces the ICD's
CS100_1-50 verbatim). One table, one decoder, so the two cannot drift apart. =#

